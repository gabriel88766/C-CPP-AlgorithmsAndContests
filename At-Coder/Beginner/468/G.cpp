int main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    //freopen("in", "r", stdin); //test input
    init();
    int n;
    string s;
    cin >> n >> s;
    if(s[0] != 'o' || s.back() != 'o') cout << "0\n";
    else{
        int lo = 0;
        vector<int> v;
        for(int i=1;i<n;i++){
            if(s[i] == 'o'){
                v.push_back(i - lo + 1);
                lo = i;
            }
        }
        Mint ans = 1;
        vector<Mint> oeis(n+1);
        oeis[1] = 1;
        for(int i=2;i<=n;i++){
            oeis[i] = fat[i];
            for(int j=i-1;j>=2;j--) oeis[i] -= fat[j] * oeis[i - j + 1];
        }
        for(auto x : v) ans *= oeis[x];
        cout << ans << "\n";
    }
}
